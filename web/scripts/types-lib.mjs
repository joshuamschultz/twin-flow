// Builds web/src/decision/types.ts from the JSON Schemas in src/twinflow/report/schemas/.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { format } from "prettier";

const web = fileURLToPath(new URL("..", import.meta.url));
export const SCHEMAS = join(web, "../src/twinflow/report/schemas");
export const TYPES = join(web, "src/decision/types.ts");

export async function typesText() {
  const files = readdirSync(SCHEMAS)
    .filter((f) => f.endsWith(".schema.json"))
    .sort();
  const parts = [
    "/* Generated by web/scripts/gen-types.mjs from src/twinflow/report/schemas/*.schema.json.",
    "   Do not edit. Run: npm run gen:types */",
    "",
  ];
  for (const file of files) {
    const schema = JSON.parse(readFileSync(join(SCHEMAS, file), "utf8"));
    const ts = await compile(schema, schema.title, {
      bannerComment: "",
      additionalProperties: false,
      unreachableDefinitions: true,
      style: { printWidth: 100 },
    });
    parts.push(ts.trim(), "");
  }
  return format(parts.join("\n"), { parser: "typescript" });
}
