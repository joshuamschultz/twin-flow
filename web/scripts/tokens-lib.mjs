// Pure helpers behind export-tokens.mjs, shared with the vitest staleness test.
// Reads the light block (`:root { }`) and the dark block (`:root[data-theme="dark"] { }`)
// of each CSS file and resolves var() references inside the same theme.

const BLOCK = /(:root(?:\[data-theme="dark"\])?)\s*\{([^{}]*)\}/g;
const DECL = /(--[a-z0-9-]+)\s*:\s*([^;]+);/gi;

export function readBlocks(css) {
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const out = { light: {}, dark: {} };
  for (const [, selector, body] of clean.matchAll(BLOCK)) {
    const theme = selector.includes("dark") ? "dark" : "light";
    for (const [, name, value] of body.matchAll(DECL)) {
      out[theme][name] = value.replace(/\s+/g, " ").trim();
    }
  }
  return out;
}

function resolve(value, table, depth = 0) {
  if (depth > 10) return value;
  return value.replace(
    /var\((--[a-z0-9-]+)(?:,\s*([^)]+))?\)/gi,
    (_, name, fallback) => {
      const hit = table[name] ?? fallback;
      return hit === undefined
        ? `var(${name})`
        : resolve(hit, table, depth + 1);
    },
  );
}

/** tokens.json content from the CSS texts, brand layer first. */
export function buildTokens(cssTexts) {
  const light = {};
  const dark = {};
  for (const css of cssTexts) {
    const blocks = readBlocks(css);
    Object.assign(light, blocks.light);
    Object.assign(dark, blocks.dark);
  }
  const darkAll = { ...light, ...dark };
  const pick = (table, keep) =>
    Object.fromEntries(
      Object.keys(keep)
        .sort()
        .filter((k) => k.startsWith("--ba-") || k.startsWith("--tf-"))
        .map((k) => [k, resolve(table[k], table)]),
    );
  return {
    about:
      "Generated by web/scripts/export-tokens.mjs from web/src/index.css and web/src/decision/tokens.css. Do not edit.",
    light: pick(light, light),
    dark: pick(darkAll, darkAll),
  };
}

export function tokensText(cssTexts) {
  return JSON.stringify(buildTokens(cssTexts), null, 2) + "\n";
}
